// Precompiles schemas/record-v1.schema.json into src/validate.generated.ts with ajv's standalone
// mode, so validating needs no eval/new Function at runtime (works under a strict CSP).
// Run after changing the schema: npm run gen
import { readFileSync, writeFileSync } from 'node:fs'
import { Ajv2020 } from 'ajv/dist/2020.js'
import standaloneCode from 'ajv/dist/standalone/index.js'

const schema = JSON.parse(readFileSync(new URL('../schemas/record-v1.schema.json', import.meta.url), 'utf8'))
const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true, esm: true } })
const validate = ajv.compile(schema)
let code = standaloneCode.default ? standaloneCode.default(ajv, validate) : standaloneCode(ajv, validate)
// The standalone code still require()s two tiny ajv runtime helpers, which doesn't work in ESM or
// browsers. Replace them with local equivalents so the output has no imports at all.
const helpers = {
  'ajv/dist/runtime/equal': '__equal',
  'ajv/dist/runtime/ucs2length': '__ucs2length',
}
code = code.replace(/require\("(ajv\/dist\/runtime\/[a-z0-9]+)(?:\.js)?"\)\.default/g, (_, p) => {
  if (!helpers[p]) throw new Error(`unexpected ajv runtime helper ${p}`)
  return helpers[p]
})
if (/require\(/.test(code)) throw new Error('generated validator still contains require()')
const prelude = `const __equal = (a, b) => {
  if (a === b) return true
  if (a && b && typeof a === 'object' && typeof b === 'object') {
    if (Array.isArray(a) !== Array.isArray(b)) return false
    const ka = Object.keys(a)
    if (ka.length !== Object.keys(b).length) return false
    return ka.every((k) => Object.prototype.hasOwnProperty.call(b, k) && __equal(a[k], b[k]))
  }
  return a !== a && b !== b
}
const __ucs2length = (s) => [...s].length
`
code = code.replace('"use strict";', `"use strict";${prelude}`)
writeFileSync(new URL('../src/validate.generated.ts', import.meta.url), `// @ts-nocheck\n// GENERATED by tool/gen-validator.mjs from schemas/record-v1.schema.json. Do not edit.\n${code}\n`)
console.log('wrote src/validate.generated.ts')
